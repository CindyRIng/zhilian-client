export function cityNameOf(code: string): string | undefined {
  return CITY_SEED.find((c) => c.code === code)?.name;
}

export function filterCities(level: CitySeed['level'] | undefined, defaults: string[]): Array<CitySeed & { isDefault: boolean }> {
  const set = new Set(defaults);
  const list = level ? CITY_SEED.filter((c) => c.level === level) : CITY_SEED;
  return list.map((c) => ({ ...c, isDefault: set.has(c.code) }));
}
